// Generates docs/PATTERNS.md from the detectors in core.js.
//
// The tooltip on every highlight is the matching pattern's `name`, so that
// file is the user-facing answer to "what does this tooltip mean?". Deriving
// it from core.js keeps the doc honest: the engine is a verbatim port of
// upstream's `impl` section, and a hand-written list would drift the moment
// upstream adds a detector.
//
// Run with: node tools/gen-patterns-doc.mjs

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const core = createRequire(import.meta.url)(path.join(root, 'core.js'));

// Which detectors actually attach a counter badge, determined by running them
// rather than by reading the source: a pattern earns a badge if any match it
// produces carries one.
const enabled = new Set(core.patterns.map((p) => p.id));
const { matches } = core.collectMatches(core.EXAMPLE, enabled);
const badged = new Set(
  matches.filter((m) => m.badge != null).map((m) => m.patternId));
const seen = new Map();
for (const m of matches) {
  if (!seen.has(m.patternId)) {
    seen.set(m.patternId, core.EXAMPLE.slice(m.start, m.end).replace(/\s+/g, ' '));
  }
}

const cell = (s) => String(s).replace(/\|/g, '\|').replace(/\n/g, ' ');

const rows = core.patterns.map((p) => {
  const tip = '`' + cell(p.name) + '`' + (badged.has(p.id) ? ' ᴮ' : '');
  return '| ' + tip + ' | `' + p.id + '` | ' + cell(p.description) + ' |';
});

const out = `# Pattern reference

<!-- Generated by tools/gen-patterns-doc.mjs — do not edit by hand. -->

Every highlight carries a tooltip. **That tooltip is the name of the detector
that fired, not a suggested rewrite.** The names are written as templates, so
they rarely match the words on your page verbatim:

| In the tooltip | Means |
| --- | --- |
| \`X\`, \`Y\` | a slot filled by whatever words the page used |
| \`VERB\` | a slot filled by any verb |
| \`…\` | a variable middle of any length |

For example, hovering the highlight on *"No sign-ups, no downloads, no hassle"*
shows \`“No X, no Y” chains · 3 “no” items\`. The first half names the pattern.
The half after the middle dot is the badge detail, present only on chain-style
detectors, and it counts the items in the chain. The small superscript number
rendered at the end of a chain highlight has its own shorter tooltip carrying
just that count.

Rows marked **ᴮ** below are the chain-style detectors that add a badge.

## The detectors

The extension ships ${core.patterns.length} detectors. They are a verbatim port of the \`impl\` section of Simon Willison's
[llm-cliche-highlighter](https://github.com/simonw/tools/blob/main/llm-cliche-highlighter.html),
covering rhetorical tics and the tells catalogued in Wikipedia's
[Signs of AI writing](https://en.wikipedia.org/wiki/Wikipedia:Signs_of_AI_writing).
There is no per-detector toggle; the extension is one button, and all of them
run on every click.

| Tooltip (pattern name) | id | What it detects |
| --- | --- | --- |
${rows.join('\n')}

## Seen on the bundled example

These are real matches from the example text the upstream tool ships, which is
also what \`test-page.html\` is built from. Left is what gets highlighted, right
is what the tooltip says.

| Highlighted text | Tooltip |
| --- | --- |
${[...seen.entries()].slice(0, 12).map(([id, text]) => {
  const p = core.patternsById[id];
  const m = matches.find((x) => x.patternId === id);
  const trimmed = text.length > 52 ? text.slice(0, 49) + '…' : text;
  return '| ' + cell(trimmed) + ' | `' +
    cell(core.matchTipText(p.name, m.badgeTitle)) + '` |';
}).join('\n')}

Regenerate this file with \`node tools/gen-patterns-doc.mjs\`.
`;

writeFileSync(path.join(root, 'docs', 'PATTERNS.md'), out, 'utf8');
console.log('docs/PATTERNS.md written (' + core.patterns.length + ' detectors, ' +
  badged.size + ' with badges)');
